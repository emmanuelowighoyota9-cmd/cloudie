/**
 * Platform-wide secret sealing.
 *
 * ONE implementation for the whole platform, absorbing the narrower
 * `vtuCrypto.ts` that slice 1 shipped. Two independent crypto modules with two
 * formats is a liability: whichever is less carefully reviewed is the one that
 * leaks a credential.
 *
 * ── Why WebCrypto and not node:crypto ──────────────────────────────
 * Sealing happens in two runtimes. The ADMIN path seals inside a V8 mutation
 * (an admin creating a provider sends a plaintext key that must be sealed at
 * the boundary), while the call path opens inside a "use node" action.
 * `node:crypto` is only available in the second, so a node-only helper would
 * make the admin CRUD impossible.
 *
 * `crypto.subtle` is available in BOTH Convex runtimes and is async, which is
 * why `encrypt`/`decrypt` return promises. One implementation, one format, no
 * runtime split.
 *
 * ── Master key ─────────────────────────────────────────────────────
 * `APP_MASTER_KEY` is the current primary, read HERE and never passed as an
 * argument: a key that must be threaded through every call site is a key that
 * eventually gets handed to the wrong function.
 *
 * `VTU_ENCRYPTION_SECRET` is accepted for DECRYPTION ONLY, as a legacy ring
 * entry. It can no longer seal anything. It exists because slice 1 sealed
 * provider rows under that name; without it those rows would become
 * undecryptable the moment this module shipped. Remove once no sealed row
 * predates the cutover.
 *
 * ── Ciphertext format ──────────────────────────────────────────────
 * Self-describing, so a future algorithm or key change is DETECTABLE rather
 * than silently producing garbage:
 *
 *   cex1.<alg>.<kid>.<iv>.<tag>.<ct>
 *      │     │     │      │     │    └─ AES-256-GCM ciphertext
 *      │     │     │      │     └────── 16-byte GCM auth tag
 *      │     │     │      └──────────── 12-byte random IV
 *      │     │     └─────────────────── key id — which master key sealed this
 *      │     └───────────────────────── algorithm tag
 *      └─────────────────────────────── format version
 *
 * The `kid` field is what makes rotation possible without downtime. Without it
 * a new key produces a payload indistinguishable from a wrong key or a tampered
 * row, forcing rotation to be all-or-nothing.
 *
 * A legacy `v1:<iv>.<tag>.<ct>` payload (slice 1's format) is also accepted and
 * is tried against every key in the ring, since it carries no key id.
 *
 * ── Key derivation ─────────────────────────────────────────────────
 * SHA-256(salt ‖ secret) via WebCrypto. This is a KDF, not a password hash,
 * and it is appropriate only because the master key is high-entropy random
 * material generated by the operator — NOT a human-chosen passphrase. A weak
 * master key weakens the derivation and cannot be fixed by this code.
 *
 * ── Rotation policy (DECIDED, NOT IMPLEMENTED) ─────────────────────
 * Versioned keys with lazy re-seal. `APP_MASTER_KEY` is the primary; retired
 * keys stay readable under their `kid` and leave the ring only once no live row
 * needs them. Rows re-seal with the primary the next time they are
 * legitimately decrypted, so there is no stop-the-world window in which every
 * sealed row is briefly unreadable.
 *
 * The rejected alternative was rotate-in-place: set the new key, then re-seal
 * every row. Simpler, one code path, but a crash midway leaves a half-rotated
 * system where some rows work and some throw, with no partial rollback. It
 * converts a routine security task into a maintenance window.
 *
 * This slice implements NEITHER policy. It lays the groundwork only: a `kid`
 * field, a key ring, and a primary/legacy distinction. Actual rotation needs a
 * sweeper for never-touched rows and a `kid` retirement procedure.
 */

const FORMAT = "cex1";

/**
 * Algorithm identifier.
 *
 * MUST be the normalized uppercase form. WebCrypto validates algorithm names
 * case-sensitively, unlike `node:crypto`, so a lowercase "aes-256-gcm" throws
 * NotSupportedError at `importKey`.
 */
const ALG = "AES-GCM";

/** Lowercase tag stored in the ciphertext, for humans reading the format. */
const ALG_TAG = "aes-256-gcm";
const HKDF_SALT = new TextEncoder().encode("crestline.secrets.v1");

/** Key ids. `master` is the current primary; `legacy` is read-only. */
export const KEY_ID_MASTER = "master";
export const KEY_ID_LEGACY = "legacy";

export type SecretErrorCode =
  | "ENCRYPTION_KEY_NOT_CONFIGURED"
  | "MALFORMED_CIPHERTEXT"
  | "UNSUPPORTED_FORMAT"
  | "UNKNOWN_KEY_ID"
  | "DECRYPTION_FAILED";

/**
 * A sealed-value failure, carrying a code rather than a message.
 *
 * The message is generic on purpose: it never echoes the plaintext, the
 * ciphertext, the key, or any part of them, because these errors routinely
 * reach an admin UI and an audit log.
 */
export class SecretError extends Error {
  readonly code: SecretErrorCode;

  constructor(code: SecretErrorCode) {
    super(`Secret error: ${code}`);
    this.name = "SecretError";
    this.code = code;
  }
}

export function isSecretError(error: unknown): error is SecretError {
  return error instanceof SecretError;
}

/**
 * The master key ring, primary first.
 *
 * `APP_MASTER_KEY` is the only key permitted to SEAL. `VTU_ENCRYPTION_SECRET`
 * is a read-only compatibility entry for rows sealed before the cutover.
 */
function keyRing(): Array<{ kid: string; secret: string }> {
  const ring: Array<{ kid: string; secret: string }> = [];
  const primary = process.env.APP_MASTER_KEY;
  if (primary) ring.push({ kid: KEY_ID_MASTER, secret: primary });
  const legacy = process.env.VTU_ENCRYPTION_SECRET;
  if (legacy && legacy !== primary) {
    ring.push({ kid: KEY_ID_LEGACY, secret: legacy });
  }
  return ring;
}

function requirePrimary(): string {
  const primary = process.env.APP_MASTER_KEY;
  if (!primary) throw new SecretError("ENCRYPTION_KEY_NOT_CONFIGURED");
  return primary;
}

function toBase64(bytes: Uint8Array): string {
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary);
}

function fromBase64(value: string): Uint8Array {
  const binary = atob(value);
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) out[i] = binary.charCodeAt(i);
  return out;
}

/** Derive a fixed-length AES key from an arbitrary-length master secret. */
async function deriveKey(secret: string): Promise<CryptoKey> {
  const material = new TextEncoder().encode(secret);
  const combined = new Uint8Array(HKDF_SALT.length + material.length);
  combined.set(HKDF_SALT, 0);
  combined.set(material, HKDF_SALT.length);

  const digest = await crypto.subtle.digest("SHA-256", combined);
  return crypto.subtle.importKey("raw", digest as unknown as BufferSource, { name: ALG }, false, [
    "encrypt",
    "decrypt",
  ]);
}

/**
 * Seal a plaintext secret.
 *
 * Always uses the current primary, so every new value is readable by the
 * current key and the ring converges over time.
 */
export async function encrypt(plaintext: string): Promise<string> {
  if (!plaintext) throw new SecretError("MALFORMED_CIPHERTEXT");

  const key = await deriveKey(requirePrimary());
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const buffer = await crypto.subtle.encrypt(
    { name: ALG, iv: iv as unknown as BufferSource },
    key,
    new TextEncoder().encode(plaintext) as unknown as BufferSource,
  );

  // WebCrypto returns iv ‖ ciphertext ‖ tag. Split the tag out so the stored
  // format carries it as a distinct field.
  const bytes = new Uint8Array(buffer);
  const tag = bytes.slice(bytes.length - 16);
  const ciphertext = bytes.slice(0, bytes.length - 16);

  return [
    FORMAT,
    ALG_TAG,
    KEY_ID_MASTER,
    toBase64(iv),
    toBase64(tag),
    toBase64(ciphertext),
  ].join(".");
}

/** Open a value sealed by {@link encrypt}, or a legacy `v1:` payload. */
export async function decrypt(payload: string): Promise<string> {
  if (typeof payload !== "string" || payload.length === 0) {
    throw new SecretError("MALFORMED_CIPHERTEXT");
  }
  if (payload.startsWith(`${FORMAT}.`)) return decryptCurrent(payload);
  if (payload.startsWith("v1:")) return decryptLegacy(payload);
  throw new SecretError("UNSUPPORTED_FORMAT");
}

async function decryptCurrent(payload: string): Promise<string> {
  const parts = payload.split(".");
  // cex1 | alg | kid | iv | tag | ct
  if (parts.length !== 6) throw new SecretError("MALFORMED_CIPHERTEXT");
  const [, alg, kid, ivPart, tagPart, dataPart] = parts;

  if (alg !== ALG_TAG) throw new SecretError("UNSUPPORTED_FORMAT");

  // Resolve the key FIRST so an unknown key id is reported as such rather than
  // as a generic decryption failure.
  const entry = keyRing().find((k) => k.kid === kid);
  if (!entry) throw new SecretError("UNKNOWN_KEY_ID");

  return open(entry.secret, ivPart, tagPart, dataPart);
}

/** Slice 1's format: `v1:<iv>.<tag>.<ct>`, with no key id. */
async function decryptLegacy(payload: string): Promise<string> {
  const [ivPart, tagPart, dataPart] = payload.slice(3).split(".");
  if (!ivPart || !tagPart || !dataPart) {
    throw new SecretError("MALFORMED_CIPHERTEXT");
  }

  const ring = keyRing();
  if (ring.length === 0) throw new SecretError("ENCRYPTION_KEY_NOT_CONFIGURED");

  // No key id to go on, so try each. Every failure is a GCM tag mismatch, so a
  // wrong key and a tampered payload are genuinely indistinguishable here — we
  // surface the generic code rather than pretending to tell them apart.
  for (const entry of ring) {
    try {
      return await open(entry.secret, ivPart, tagPart, dataPart);
    } catch {
      // try the next key
    }
  }
  throw new SecretError("DECRYPTION_FAILED");
}

async function open(
  secret: string,
  ivPart: string,
  tagPart: string,
  dataPart: string,
): Promise<string> {
  const key = await deriveKey(secret);
  const iv = fromBase64(ivPart);
  const tag = fromBase64(tagPart);
  const ciphertext = fromBase64(dataPart);

  // WebCrypto expects tag appended to the ciphertext, so rejoin them.
  const combined = new Uint8Array(ciphertext.length + tag.length);
  combined.set(ciphertext, 0);
  combined.set(tag, ciphertext.length);

  const buffer = await crypto.subtle.decrypt(
    { name: ALG, iv: iv as unknown as BufferSource },
    key,
    combined as unknown as BufferSource,
  );
  return new TextDecoder().decode(buffer);
}

/**
 * Open a secret, returning a typed failure instead of throwing.
 *
 * For call sites that must not surface a raw exception to a client — a
 * provider row with a corrupt credential should produce `CREDENTIAL_CORRUPT`,
 * not an unhandled error escaping an action.
 */
export async function tryDecrypt(
  payload: string,
): Promise<{ ok: true; value: string } | { ok: false; code: SecretErrorCode }> {
  try {
    return { ok: true, value: await decrypt(payload) };
  } catch (error) {
    if (isSecretError(error)) return { ok: false, code: error.code };
    return { ok: false, code: "DECRYPTION_FAILED" };
  }
}
